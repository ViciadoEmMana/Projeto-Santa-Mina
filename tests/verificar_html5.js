const fs=require('node:fs');const vm=require('node:vm');const assert=require('node:assert/strict');
const html=fs.readFileSync('html5/principal/index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(x=>x.trim());
assert.ok(scripts.length>0,'É necessário JavaScript incorporado');
for(const code of scripts)new vm.Script(code,{filename:'html5/principal/index.html'});
const match=html.match(/const chapters=\[([\s\S]*?)\];/);
assert.ok(match,'capítulos presentes');
const formations=[...match[1].matchAll(/enemies:\[([^\]]+)\]/g)].map(m=>m[1].replace(/['\s]/g,''));
assert.deepEqual(formations,['archer_bandit,club_bandit','club_goblin,knife_goblin','scrap_goblin,bow_goblin,knife_goblin','tripa_seca,bow_goblin,club_goblin']);
assert.ok(html.includes("enemy.weaponPassive==='club'&&natural===6"),'passiva porrete');
assert.ok(html.includes("enemy.weaponPassive==='sword'&&natural===1"),'passiva espada do chefe');
assert.ok(html.includes('const df=visibleDefense(u)'), 'defesa acima das unidades');
assert.ok(html.includes('hero.knocked=false'), 'recuperação do derrubado');
assert.ok(html.includes("const preferred=e.ranged?[5,4]:[3]"), 'arqueiro no fundo');
assert.ok(html.includes('state.hero.ap=Math.max(0,state.hero.ap-1)'), 'Derrubado reduz somente um PA do herói');
assert.ok(html.includes('enemy.apLeft=Math.max(0,enemy.ap-(enemy.knocked?1:0))'), 'Derrubado reduz somente um PA do inimigo');
assert.ok(html.includes("proneAdvantage=!!hero.knocked"), 'ataques dos inimigos têm vantagem contra herói Derrubado');
assert.ok(html.includes("proneAdvantage=!!target.knocked"), 'ataques do herói têm vantagem contra inimigo Derrubado');
assert.ok(html.includes("rollMode==='max'?Math.max(...rolls)"), 'maior dado utilizado na vantagem');
assert.ok(html.includes("const extraRolls=enemy.count>1"), 'dois golpes usam rolagens distintas');
assert.ok(html.includes('clearKnockedAfterTurn(enemy)'), 'status removido ao final do turno do inimigo');
assert.ok(html.includes('clearKnockedAfterTurn(state.hero)'), 'status removido ao final do turno do herói');
assert.ok(!html.includes('perdeu o turno por Derrubado'), 'regra antiga de perder turno deve ser removida');
assert.ok(html.includes("base>=6||damage>=hero.hp+hero.tempHp"), 'Muralha gatilho ataque total 6+');
assert.ok(html.includes("wallReason=fatal?"), 'Muralha motivo visual');
assert.ok(html.includes("const extraRolls=enemy.count>1?dice"), 'Faca dupla sempre rola segundo dado');
assert.ok(html.includes("strikes=enemy.count>1?raw.filter(v=>v!==1):raw"), 'Faca natural 1 nao soma dano');
assert.ok(html.includes("strikes.reduce((a,b)=>a+b,0)+(strikes.length?enemyDamageStat(enemy):0)"), 'Faca soma atributo uma vez se acertar');
assert.equal(([3,4].filter(x=>x!==1).reduce((a,b)=>a+b,0)+2),9,'3 e 4 causam 9 de dano bruto');
assert.equal(([1,4].filter(x=>x!==1).reduce((a,b)=>a+b,0)+2),6,'1 e 4 causam 6 de dano bruto');
assert.equal(([1,1].filter(x=>x!==1).reduce((a,b)=>a+b,0)),0,'dois resultados 1 causam 0 de dano bruto');
assert.ok(html.includes("if(natural===1&&target===hero&&enemy.count===1)"), 'Erro da primeira faca nao cancela a segunda');
assert.ok(html.includes("scrap_goblin:[1,3],bow_goblin:[1,5],knife_goblin:[2,3]"), 'Formacao 3 garante arqueiro na coluna 6');
assert.ok(html.includes("tripa_seca:[1,3],bow_goblin:[1,5],club_goblin:[2,4]"), 'Formacao boss com arqueiro ao fundo e porrete lateral atras');
assert.ok(html.includes("state.hero.movedThisTurn=true"), 'Deslocamento marca acao usada');
assert.ok(html.includes("state.hero.movedThisTurn=false"), 'Deslocamento reinicia');
assert.ok(html.includes("(['move','run'].includes(c.id)&&h.movedThisTurn)"), 'UI desabilita ambas cartas apos uma');
// Exercita a função real de Defesa isoladamente, sem navegador.
const defenseCode=html.match(/function defense\(target,attackNatural\)\{[\s\S]*?return visibleDefense\(target\)\}/)?.[0];
assert.ok(defenseCode,'função de Defesa encontrada');
const combatContext=vm.createContext({state:{hero:{hp:14,defending:false,veteranDef:false}},heroType:()=> 'brokk',heroShield:()=>true,visibleDefense:()=>0,Array});
vm.runInContext(defenseCode,combatContext);
const df=(faces)=>combatContext.defense(combatContext.state.hero,faces);
assert.equal(df([1,4]),1,'nenhuma faca ativa escudo');
assert.equal(df([1,2]),3,'segunda faca 2 ativa +2');
assert.equal(df([3,4]),3,'primeira faca 3 ativa +2');
assert.equal(df([2,3]),3,'ambas ativam mas bônus não acumula');
assert.equal(df([3,3]),3,'dois 3 não geram +4');
assert.equal(df(2),3,'escudo também funciona em ataque simples');
assert.equal(df(4),1,'sem gatilho em ataque simples');
combatContext.state.hero.defending=true;
assert.equal(df([2,3]),5,'Defender +2 soma ao escudo +2 uma vez e pele +1');
combatContext.state.hero.hp=7;
assert.equal(df([2,3]),4,'Pele de Rocha é removida com PV <= 7');
const enemyStats=html.match(/const monsters=\{([\s\S]*?)\n\};/)?.[1];
assert.ok(enemyStats,'catálogo de monstros presente');
assert.ok(enemyStats.includes("bow_goblin:{name:'Goblin Tiro Certo'"),'arqueiro presente');
assert.ok(enemyStats.includes('die:6,count:1,bonus:2,ranged:true'),'arqueiro sem antigo -1');
assert.ok(!enemyStats.includes('bonus:-1'),'nenhum bônus negativo antigo');
const enemyBonusCode=html.match(/const enemyDamageStat=enemy=>[^;]+;/)?.[0];
assert.ok(enemyBonusCode,'bônus é calculado segundo a arma');
const combatStats=vm.createContext({});
vm.runInContext(enemyBonusCode,combatStats);
const stat=combatStats.enemyDamageStat;
assert.equal(stat({ranged:true,count:1,dex:2,for:0}),2,'arco usa DES');
assert.equal(stat({ranged:false,count:2,dex:2,for:0}),2,'duas facas usam DES uma vez');
assert.equal(stat({ranged:false,count:1,dex:1,for:2}),2,'porrete/espada/gancho usam FOR');
assert.ok(html.includes("strikes.length?enemyDamageStat(enemy):0"),'duas facas somam atributo somente quando acertam');
assert.ok(html.includes("raw.reduce((a,b)=>a+b,0)+enemyDamageStat(enemy)"),'ataque único soma atributo correto');
assert.equal(4+stat({ranged:true,count:1,dex:2,for:0}),6,'arqueiro com dado 4 causa 6 bruto');
assert.ok(html.includes("if(heroType()==='zeno'&&natural>=5){if(!hero.veteranAtk)"),'1º dado 5+ ativa ataque');
assert.ok(html.includes("else if(!hero.veteranDef){hero.veteranDef=true"),'2º dado 5+ ativa Defesa');
assert.ok(!html.includes("Bloqueio sem dano: +1 Defesa até o fim do combate"),'Defesa do veterano não ativa mais por bloqueio');
const veteranTrigger=(hero,n)=>{if(n>=5){if(!hero.veteranAtk)hero.veteranAtk=true;else if(!hero.veteranDef)hero.veteranDef=true;}};
let zeno={veteranAtk:false,veteranDef:false};
veteranTrigger(zeno,4);assert.equal(zeno.veteranAtk,false);
veteranTrigger(zeno,5);assert.equal(zeno.veteranAtk,true);assert.equal(zeno.veteranDef,false);
veteranTrigger(zeno,6);assert.equal(zeno.veteranDef,true);
veteranTrigger(zeno,5);assert.equal(zeno.veteranAtk,true);assert.equal(zeno.veteranDef,true);
console.log('HTML válido: arco usa DES, Faca Dupla com bônus único e Veterano de Batalha progressivo.');
